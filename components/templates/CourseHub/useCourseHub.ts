export function useCourseHub(props: CourseHubProps) {
  const key: CourseGroup = props.group && GROUPS[props.group] ? props.group : "elementary";
  const g = GROUPS[key];
  const n = g.steps.length;
  return {
    g,
    n,
    c: PALETTES[key],
    steps: g.steps.map((s, i) => ({ ...s, no: i + 1, lift: n - 1 - i })),
    feats: g.feats.map(([t, d], i) => ({ n: i + 1, t, d })),
  };
}

export type CourseHubVals = ReturnType<typeof useCourseHub>;
